// 주문 추가: 월결제 추가 질문을 [취소]한 뒤(결제 방식 미정) [접수]를 누르면 요청이 나가는가. 가짜 서버(mock 5174)
const { chromium } = require('C:/Users/SSAFY/AppData/Local/Temp/pw/node_modules/playwright-core')
;(async () => {
  const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
  const page = await (await browser.newContext({ viewport: { width: 1440, height: 900 } })).newPage()
  const sent = []
  page.on('request', (r) => { const u = new URL(r.url()); if (u.pathname.startsWith('/api/') && r.method() !== 'GET' && !u.pathname.endsWith('/login')) sent.push(`${r.method()} ${u.pathname}`) })
  const res = []
  page.on('response', (r) => { const u = new URL(r.url()); if (u.pathname === '/api/admin/orders') res.push(`${r.status()} ${r.request().method()} ${u.pathname}`) })
  const wait = (ms) => page.waitForTimeout(ms)
  await page.goto('http://localhost:5174/login'); await page.waitForSelector('input')
  const ins = await page.$$('input'); await ins[0].fill('admin'); await ins[1].fill('test1234'); await page.keyboard.press('Enter')
  await page.waitForURL((u) => !u.pathname.startsWith('/login'))
  await page.goto('http://localhost:5174/orders'); await wait(1500)
  await page.getByRole('button', { name: /주문 추가/ }).first().click(); await wait(700)
  const dlg = () => page.locator('dialog[open]').last()
  const combo = (i) => dlg().locator('input[role=combobox]').nth(i)
  await combo(0).click(); await combo(0).fill('박지호'); await wait(1300); await combo(0).press('ArrowDown'); await combo(0).press('Enter'); await wait(1300)
  await combo(2).click(); await wait(1300); await combo(2).press('ArrowDown'); await combo(2).press('Enter'); await wait(500)
  await dlg().getByLabel('소박스 개수').fill('1')
  await dlg().locator('label:has-text("물품 가액") select').selectOption({ index: 1 })
  const go = () => page.locator('dialog[open]').first().getByRole('button', { name: /^접수$/ })
  await go().click(); await wait(1000)
  console.log('월결제 추가 질문 창:', (await page.locator('dialog[open]').count()) > 1 ? '뜸' : '안 뜸')
  await page.locator('dialog[open]').last().getByRole('button', { name: /^취소$/ }).click(); await wait(600)
  console.log('[취소] 뒤 [접수] aria-disabled:', await go().getAttribute('aria-disabled'), '| 안내:', /결제 방식을 골라 주세요/.test(await dlg().innerText()) ? '결제 방식을 골라 주세요.' : '없음')
  const before = sent.length
  await go().click({ force: true }); await wait(1500)
  console.log('미정인 채 [접수] → 나간 저장 요청:', sent.slice(before).join(', ') || '없음')
  await dlg().getByText('개인카드', { exact: true }).click(); await wait(400)
  console.log('개인카드 고른 뒤 aria-disabled:', await go().getAttribute('aria-disabled'))
  await go().click(); await wait(2000)
  console.log('개인카드로 [접수] → 요청:', sent.slice(before).join(', ') || '없음', '| 응답:', res.join(', ') || '없음', '| 주소:', new URL(page.url()).pathname, '| 창 글 끝:', (await page.locator('dialog[open]').count()) ? (await dlg().innerText()).replace(/\s+/g, ' ').slice(-70) : '창 닫힘')
  await browser.close()
})().catch((e) => { console.log('실패:', String(e.message).slice(0, 300)); process.exit(1) })
